/// Хранит единственную активную или приостановленную сессию.
protocol SessionRepository: Sendable {
    /// Загружает сохранённую сессию, если она существует и декодируется.
    func load() -> SessionState?

    /// Полностью заменяет сохранённое состояние сессии.
    func save(_ state: SessionState)

    /// Удаляет активную сессию без сохранения истории.
    func clear()
}
